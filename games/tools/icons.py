def main():
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
    made = 0
    for gid, grid in ICONS.items():
        d = os.path.join(root, 'src', gid)
        if not os.path.isdir(d):
            continue
        p, n = build('icon', grid, P, d, scale=2)
        print("%-10s -> %s (%d b)" % (gid, p, n))
        made += 1
    print("icons made:", made)

main()
